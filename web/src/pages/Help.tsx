/** Раздел справки. Открывается сам, если ссылка ведёт на него (#id) — кнопка «?» на страницах. */
function Topic({ title, children, open = false, id }: { title: string; children: ReactNode; open?: boolean; id?: string }) {
  const target = !!id && typeof location !== 'undefined' && location.hash === `#${id}`;
  return (
    <details id={id} open={open || target} className={`card group scroll-mt-20 overflow-hidden ${target ? 'ring-2 ring-brand-400' : ''}`}
      ref={(el) => { if (el && target) setTimeout(() => el.scrollIntoView({ block: 'start' }), 50); }}>
      <summary className="flex cursor-pointer list-none items-center justify-between gap-4 px-6 py-4 font-semibold hover:bg-slate-50 dark:hover:bg-slate-800/40">
        {title}
        <ChevronDown className="size-5 shrink-0 text-slate-400 transition group-open:rotate-180" />
      </summary>
      <div className="help border-t border-slate-100 px-6 py-5 text-[15px] leading-relaxed text-slate-700 dark:border-slate-800 dark:text-slate-300">{children}</div>
    </details>
  );
}

