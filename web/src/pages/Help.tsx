import type { ReactNode } from 'react';
import { BookOpen, ChevronDown, ShieldCheck } from 'lucide-react';
import { PageHeader } from '../components/ui';

function Topic({ title, children, open = false }: { title: string; children: ReactNode; open?: boolean }) {
  return (
    <details open={open} className="card group overflow-hidden">
      <summary className="flex cursor-pointer list-none items-center justify-between gap-4 px-6 py-4 font-semibold hover:bg-slate-50 dark:hover:bg-slate-800/40">
        {title}
        <ChevronDown className="size-5 shrink-0 text-slate-400 transition group-open:rotate-180" />
      </summary>
      <div className="help border-t border-slate-100 px-6 py-5 text-[15px] leading-relaxed text-slate-700 dark:border-slate-800 dark:text-slate-300">{children}</div>
    </details>
  );
}

const Steps = ({ children }: { children: ReactNode }) => <ol className="ml-5 list-decimal space-y-1.5">{children}</ol>;
const List = ({ children }: { children: ReactNode }) => <ul className="ml-5 list-disc space-y-1.5">{children}</ul>;
const Code = ({ children }: { children: ReactNode }) => <code className="rounded bg-slate-100 px-1.5 py-0.5 font-mono text-[13px] dark:bg-slate-800">{children}</code>;
const Tip = ({ children }: { children: ReactNode }) => <p className="mt-3 rounded-xl bg-brand-50 px-4 py-3 text-sm text-brand-900 dark:bg-brand-500/10 dark:text-brand-100">{children}</p>;

/** Справка для всех пользователей. */
export function UserHelp() {
  return (
    <>
      <PageHeader title="Справка" subtitle="Как войти в CRM, работать из дома и что делать, если что-то не получается." />
      <div className="flex flex-col gap-3">
        <Topic title="Первый вход по приглашению" open>
          <Steps>
            <li>Владелец CRM присылает вам ссылку-приглашение. Она одноразовая и действует 72 часа.</li>
            <li>Откройте ссылку и придумайте пароль: не короче 10 символов и без логина внутри.</li>
            <li>Готово — вы вошли. В следующий раз входите по логину и паролю.</li>
          </Steps>
          <Tip>Приглашение истекло или не открывается? Попросите владельца выдать новое.</Tip>
        </Topic>
        <Topic title="Адрес CRM">
          <p>Адрес выглядит так: <Code>https://ИМЯ-КОМПЬЮТЕРА:8443</Code>. Точный адрес даст владелец. Добавьте его в закладки браузера.</p>
        </Topic>
        <Topic title="Браузер пишет «Подключение не защищено»">
          <p>Сервер CRM использует собственный сертификат. Установите его один раз — и предупреждение исчезнет:</p>
          <Steps>
            <li>Откройте <Code>https://адрес-CRM:8443/api/tls/ca</Code> — скачается файл <Code>crm-ca.crt</Code>.</li>
            <li>Дважды щёлкните файл → «Состав» → «Отпечаток». Сверьте его с отпечатком, который назовёт владелец. Не совпадает — не устанавливайте и сообщите владельцу.</li>
            <li>«Установить сертификат» → «Текущий пользователь» → «Поместить все сертификаты в следующее хранилище» → <b>«Доверенные корневые центры сертификации»</b> → «Готово».</li>
            <li>Перезапустите браузер.</li>
          </Steps>
        </Topic>
        <Topic title="Работа из дома">
          <p>Из интернета CRM напрямую не открывается — так безопаснее. Для работы из дома владелец подключит вас к защищённой сети (VPN Tailscale): вы установите программу Tailscale и войдёте по приглашению владельца. После этого CRM открывается по тому же адресу.</p>
        </Topic>
        <Topic title="Забыли пароль или сменили компьютер">
          <p>Напишите владельцу CRM: он сбросит доступ и пришлёт новую ссылку-приглашение. Старый пароль после этого перестанет работать на всех устройствах.</p>
        </Topic>
        <Topic title="Безопасность">
          <List>
            <li>Никому не сообщайте пароль — даже владельцу. Ему он не нужен.</li>
            <li>На чужом компьютере после работы нажмите «Выйти» (значок внизу меню).</li>
            <li>После 5 неверных паролей вход блокируется на 15 минут — это защита от подбора.</li>
          </List>
        </Topic>
      </div>
    </>
  );
}

