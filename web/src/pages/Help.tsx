function Topic({ title, children, open = false }: { title: string; children: ReactNode; open?: boolean }) {
  return (
    <details open={open} className="card group overflow-hidden">
      <summary className="flex cursor-pointer list-none items-center justify-between gap-4 px-6 py-4 font-semibold hover:bg-slate-50 dark:hover:bg-slate-800/40">
        {title}
        <ChevronDown className="size-5 shrink-0 text-slate-400 transition group-open:rotate-180" />
      </summary>
      <div className="help border-t border-slate-100 px-6 py-5 text-[15px] leading-relaxed text-slate-700 dark:border-slate-800 dark:text-slate-300">{children}</div>
    </details>
  );
}

const Steps = ({ children }: { children: ReactNode }) => <ol className="ml-5 list-decimal space-y-1.5">{children}</ol>;
const List = ({ children }: { children: ReactNode }) => <ul className="ml-5 list-disc space-y-1.5">{children}</ul>;
const Code = ({ children }: { children: ReactNode }) => <code className="rounded bg-slate-100 px-1.5 py-0.5 font-mono text-[13px] dark:bg-slate-800">{children}</code>;
const Tip = ({ children }: { children: ReactNode }) => <p className="mt-3 rounded-xl bg-brand-50 px-4 py-3 text-sm text-brand-900 dark:bg-brand-500/10 dark:text-brand-100">{children}</p>;

