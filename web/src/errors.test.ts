import { describe, expect, it } from 'vitest';
import { humanError } from './api';

describe('ошибки говорят, что делать', () => {
  it('нет связи', () => {
    expect(humanError(0, '')).toMatch(/Нет связи с сервером.*не сохранены.*повторите/);
  });
  it('вход закончился', () => {
    expect(humanError(401, 'нужно войти')).toBe('Вход закончился — войдите заново.');
  });
  it('нет прав — к кому идти', () => {
    expect(humanError(403, 'недостаточно прав')).toBe('Недостаточно прав — если это нужно для работы, попросите владельца.');
  });
  it('слишком часто — подождать', () => {
    expect(humanError(429, 'слишком много запросов')).toBe('Слишком много запросов. Подождите минуту и попробуйте снова.');
  });
  it('ошибка сервера — повторить или сообщить', () => {
    expect(humanError(500, 'диск')).toBe('Ошибка на сервере: диск. Повторите; если ошибка не уходит — «Сообщить о проблеме» в справке.');
  });
  it('понятные сообщения сервера не трогаем', () => {
    expect(humanError(409, 'задача в архиве — сначала верните её')).toBe('задача в архиве — сначала верните её');
    expect(humanError(403, 'из интернета одного пароля мало…')).toBe('из интернета одного пароля мало…');
  });
});
